import os
import random
import time
import zlib

from flask import Flask, jsonify, request

FLAG_PATH = os.environ.get("FLAG_PATH", "/flag/flag.txt")

app = Flask(__name__)

# Seeded accounts. jdoe's password is handed out so the session-issuance
# recipe can be observed and verified honestly; admin's password is random
# and never revealed, because reaching the admin view does not require
# logging in as admin, only predicting the session token admin already has.
USERS = {
    "jdoe": {"password": "Harvest2024!", "role": "user"},
    "admin": {"password": os.urandom(16).hex(), "role": "admin"},
}

# Session token recipe (see README): a session token is not drawn from a
# CSPRNG. It is generated by seeding Python's `random` module (a Mersenne
# Twister, not cryptographically secure) with a value computed from the
# username and the whole second at which the session was issued, then
# reading 32 hex characters off that seeded generator.
#
#   seed  = issued_at * 1_000_003 + crc32(username)
#   token = "".join(random.Random(seed).choice("0123456789abcdef")
#                    for _ in range(32))
#
# Anyone who knows a session's issuance second can recompute its token
# exactly; nothing about the token is secret beyond that one integer.
SESSIONS = {}  # token -> username

BOOT_TIME = time.time()


def issue_token(username, issued_at):
    seed = int(issued_at) * 1_000_003 + zlib.crc32(username.encode())
    rng = random.Random(seed)
    return "".join(rng.choice("0123456789abcdef") for _ in range(32))


def create_session(username, issued_at=None):
    issued_at = issued_at if issued_at is not None else time.time()
    token = issue_token(username, issued_at)
    SESSIONS[token] = username
    return token


# The admin account's session is not created by a login; it exists from the
# moment the container finished booting, the way a long-lived service
# session or a cron-started job's session might be. Nobody ever logs in as
# admin in this lab; the session is simply already there to be hijacked.
create_session("admin", BOOT_TIME)


def current_user():
    auth = request.headers.get("Authorization", "")
    if not auth.startswith("Bearer "):
        return None
    token = auth[len("Bearer "):].strip()
    username = SESSIONS.get(token)
    return USERS.get(username) if username else None


@app.route("/")
def index():
    return (
        "Root Cause lab: session-token service.\n"
        "POST /login {username, password} to sign in (jdoe / Harvest2024!).\n"
        "Send the returned token back as 'Authorization: Bearer <token>'.\n"
        "GET /time returns the server clock a session token is computed against.\n"
        "GET /admin is for admins only.\n"
    )


@app.route("/time")
def server_time():
    # Exposed so a client can compute the same issuance-second value the
    # server used, for its own session or anyone else's, with no clock-skew
    # guessing involved. uptime lets a client work out when the container
    # (and therefore admin's session) booted: boot_second = now - uptime.
    now = time.time()
    return jsonify({"now": int(now), "uptime": round(now - BOOT_TIME, 3)})


@app.route("/login", methods=["POST"])
def login():
    data = request.get_json(silent=True) or {}
    username = data.get("username")
    password = data.get("password")
    user = USERS.get(username)
    if not user or user["password"] != password:
        return jsonify({"error": "invalid credentials"}), 401
    token = create_session(username)
    return jsonify({"token": token, "role": user["role"]})


@app.route("/admin")
def admin():
    user = current_user()
    if not user:
        return jsonify({"error": "login required"}), 401
    if user["role"] != "admin":
        return jsonify({"error": "forbidden"}), 403
    with open(FLAG_PATH) as f:
        flag = f.read().strip()
    return jsonify({"flag": flag})


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=8080)
